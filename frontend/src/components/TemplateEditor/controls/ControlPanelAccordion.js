'use strict'

import React from 'react'
import classNames from 'classnames'
import PropTypes from 'prop-types'
import { ExpandableSectionToggle, Flex, FlexItem, Popover } from '@patternfly/react-core'
import HelpIcon from '@patternfly/react-icons/dist/js/icons/help-icon'
import get from 'lodash/get'

class ControlPanelAccordion extends React.Component {
  static propTypes = {
    control: PropTypes.object,
    controlData: PropTypes.array,
    controlId: PropTypes.string,
    i18n: PropTypes.func,
  }

  constructor(props) {
    super(props)
    const { collapsed = false } = props.control || {}
    this.state = { isExpanded: !collapsed }
  }

  static getDerivedStateFromProps(props, state) {
    // External collapse (e.g. collapseAboveAfterSelection) sets control.collapsed.
    if (props.control?.collapsed && state.isExpanded) {
      return { isExpanded: false }
    }
    return null
  }

  setControlSectionTitleRef = (title, ref) => {
    title.sectionTitleRef = ref
  }

  syncSectionExpanded = (isExpanded) => {
    const { control } = this.props
    if (control.sectionRef) {
      control.sectionRef.classList.toggle('collapsed', !isExpanded)
    }
    if (control.sectionTitleRef) {
      control.sectionTitleRef.classList.toggle('collapsed', !isExpanded)
    }
    if (isExpanded) {
      const { content: _content } = control
      const ref = get(_content, '[2].ref') || get(_content, '[1].ref') || get(_content, '[0].ref')
      if (ref) {
        const rect = ref.getBoundingClientRect()
        if (rect.top < 0 || rect.bottom > window.innerHeight) {
          ref.scrollIntoView({
            behavior: 'smooth',
            block: 'end',
            inline: 'nearest',
          })
        }
      }
    }
  }

  handleToggle = (isExpanded) => {
    const { control } = this.props
    if (!control.collapsable) {
      return
    }
    control.collapsed = !isExpanded
    this.setState({ isExpanded })
    this.syncSectionExpanded(isExpanded)
  }

  render() {
    const { controlId, i18n, control, controlData } = this.props
    const { tooltip, note, overline, collapsable, techPreview, titleWeight, headerAction } = control
    const { isExpanded } = this.state
    let { title, subtitle, info } = control
    if (typeof title === 'function') {
      title = title(control, controlData, i18n)
    }
    if (typeof subtitle === 'function') {
      subtitle = subtitle(control, controlData, i18n)
    }
    if (typeof info === 'function') {
      info = info(control, controlData, i18n)
    }
    const mainTitleClasses = classNames({
      'creation-view-controls-title-main': true,
      subtitle: !!subtitle,
      overline,
    })
    const titleNameClasses = classNames({
      'creation-view-controls-title-main-name': true,
      normal: titleWeight === 'normal',
    })
    const label = title || subtitle
    let id = `${controlId}-${label || ''}`
    id = id.replaceAll(/\s+/g, '-').toLowerCase()
    // Prefer the ID generated by ControlPanel.renderControlSections so aria-controls matches.
    const contentId = control.sectionContentId || `${id}-content`
    const toggleId = `${id}-toggle`

    if (control.sectionRef && !control.sectionRef.id) {
      control.sectionRef.id = contentId
    }

    const helpPopover = !info && tooltip && (
      <Popover id={`${controlId}-label-help-popover`} bodyContent={tooltip}>
        <button
          id={`${controlId}-label-help-button`}
          aria-label="More info"
          onClick={(e) => {
            e.preventDefault()
            e.stopPropagation()
          }}
          className="pf-v6-c-form__group-label-help"
        >
          <HelpIcon noVerticalAlign />
        </button>
      </Popover>
    )

    const techPreviewBadge = techPreview && (
      <div variant="primary" className="techPreviewTag">
        {i18n('creation.app.section.techPreview')}
      </div>
    )

    const titleContent = label && collapsable && (
      <div className={mainTitleClasses}>
        <Flex alignItems={{ default: 'alignItemsCenter' }} spaceItems={{ default: 'spaceItemsSm' }}>
          <FlexItem>
            <ExpandableSectionToggle
              isExpanded={isExpanded}
              onToggle={this.handleToggle}
              toggleId={toggleId}
              contentId={contentId}
            >
              <span className={titleNameClasses}>
                {label}
                {techPreviewBadge}
              </span>
            </ExpandableSectionToggle>
          </FlexItem>
          {helpPopover && <FlexItem>{helpPopover}</FlexItem>}
        </Flex>
      </div>
    )
    const staticTitleContent = label && !collapsable && (
      <div className={mainTitleClasses}>
        <div className={titleNameClasses}>
          {label}
          {techPreviewBadge}
          {helpPopover}
        </div>
      </div>
    )

    return (
      <React.Fragment>
        {label || info ? (
          <div
            id={id}
            className={classNames({
              'creation-view-controls-title': true,
              collapsed: !isExpanded,
            })}
            ref={this.setControlSectionTitleRef.bind(this, control)}
          >
            {note && <div className="creation-view-controls-note">{note}</div>}
            {headerAction && label ? (
              <Flex
                justifyContent={{ default: 'justifyContentSpaceBetween' }}
                alignItems={{ default: 'alignItemsCenter' }}
                spaceItems={{ default: 'spaceItemsMd' }}
              >
                <FlexItem grow={{ default: 'grow' }}>{titleContent || staticTitleContent}</FlexItem>
                <FlexItem>{headerAction}</FlexItem>
              </Flex>
            ) : (
              <>
                {titleContent}
                {staticTitleContent}
              </>
            )}
            {info && (
              <div className="creation-view-controls-title-normal-container">
                <div className="creation-view-controls-title-normal">{info}</div>
              </div>
            )}
          </div>
        ) : null}
      </React.Fragment>
    )
  }

}

export default ControlPanelAccordion
